"""Which WAV plays for which phone-side moment.

The files themselves live in `tincan/sounds/` (generated by scripts/gen_tones.py). Until they
exist, or if one goes missing, every slot falls back to the TTS beep so nothing is ever silent.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from tincan.tts.piper import BEEP

SOUNDS_DIR = Path(__file__).resolve().parent.parent / "sounds"
RING_ON_SECONDS = 2.0
RING_OFF_SECONDS = 4.0


def _builtin(name: str) -> Path:
    p = SOUNDS_DIR / f"{name}.wav"
    return p if p.is_file() else BEEP


@dataclass(frozen=True)
class SoundSet:
    dial_tone: Path
    call_ended: Path
    error: Path
    ringtone: Path

    @classmethod
    def default(cls, ringtone: Path | None = None) -> SoundSet:
        return cls(
            dial_tone=_builtin("dial_tone"),
            call_ended=_builtin("call_ended"),
            error=_builtin("error"),
            ringtone=ringtone if ringtone and ringtone.is_file() else _builtin("ring_classic"),
        )

    def with_ringtone(self, ringtone: Path | None) -> SoundSet:
        if ringtone is None or not ringtone.is_file():
            return self
        return SoundSet(self.dial_tone, self.call_ended, self.error, ringtone)
